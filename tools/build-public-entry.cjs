// The editor remains a single maintained source. Generate its clean public URL
// for static GitHub Pages hosting, while retaining the old URL for compatibility.
const fs = require('node:fs');
const path = require('node:path');
const assert = require('node:assert/strict');
const root = path.resolve(__dirname, '..');
const source = fs.readFileSync(path.join(root, 'tools/graphic-texture-demo.html'), 'utf8');
assert(!/<base\b/i.test(source), 'Editor already declares a base URL');
const publicHtml = source.replace('  <head>', '  <head>\n    <!-- Generated by tools/build-public-entry.cjs; edit tools/graphic-texture-demo.html. -->\n    <base href="../tools/" />');
const target = path.join(root, 'graphic-texture/index.html');
// Resolve local resources exactly as the browser will at /graphic-texture/.
const base = new URL('../tools/', 'https://synthub.art/graphic-texture/');
for (const match of publicHtml.matchAll(/(?:src|href)="([^"#]+)"/g)) {
  const url = new URL(match[1], base);
  if (url.origin !== base.origin || !/\.(?:css|js|svg|png|jpe?g|webp|woff2?)$/i.test(url.pathname)) continue;
  assert(fs.existsSync(path.join(root, decodeURIComponent(url.pathname))), 'Missing public resource: ' + url.pathname);
}
const landing = fs.readFileSync(path.join(root, 'index.html'), 'utf8');
assert(landing.includes('const targetUrl = "graphic-texture/"'));
assert(landing.includes('href="graphic-texture/"'));
if (process.argv.includes('--check')) {
  assert(fs.existsSync(target) && fs.readFileSync(target, 'utf8') === publicHtml,
    'Public entry is stale; run node tools/build-public-entry.cjs before release');
  console.log('PASS: clean public entry matches editor; homepage links and local resources resolve; legacy URL retained');
} else {
  fs.mkdirSync(path.dirname(target), { recursive: true });
  fs.writeFileSync(target, publicHtml);
  console.log('Generated graphic-texture/index.html');
}
